#!/usr/bin/env python3
"""Exercise semantic mutations through the public verifier process."""
from copy import deepcopy
from hashlib import sha256
from pathlib import Path
import argparse
import json
import subprocess


def native(binary, request):
    result = subprocess.run([binary], input=json.dumps(request), text=True, capture_output=True, check=True, timeout=20)
    return json.loads(result.stdout)


def write_packet(path, request, claim):
    payload = {"op": "verify", "request": request, "claim": claim}
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    # Ordinary hashes can be regenerated by a party changing the assertion.
    payload["sha256"] = sha256(encoded).hexdigest()
    path.write_text(json.dumps(payload, sort_keys=True))
    return payload["sha256"]


def run(binary, out):
    out.mkdir(parents=True, exist_ok=False)
    scalar = {"op": "evaluate", "expr": "sqrt(2)"}
    root = {"op": "roots", "expr": "x^2-2", "domain": [1, 2]}
    view = {"x": [-2, 2], "y": [-4, 4], "pixels": [120, 80]}
    pole = {"op": "graph", "expr": "1/x", "view": view}
    stale = {"op": "graph", "expr": "x^2", "view": view}
    rows = []
    for name, request, expected in [
        ("false-interval", scalar, "excludes the recomputed enclosure"),
        ("false-uniqueness", root, "False uniqueness evidence"),
        ("bridge-pole", pole, "bridges an unproved"),
        ("stale-geometry", stale, "Stale geometry"),
    ]:
        original = native(binary, request)
        positive = out / (name + "-positive.json")
        good_hash = write_packet(positive, request, original)
        command = [binary, "--verify", str(positive)]
        good = subprocess.run(command, capture_output=True, text=True, timeout=20)
        if good.returncode != 0:
            raise ValueError((name, good.returncode, good.stdout, good.stderr))
        rows.append({"id": name + "-positive", "argv": command, "exit": good.returncode, "stdout": good.stdout, "sha256": good_hash})
        claim = deepcopy(original)
        source = deepcopy(request)
        if name == "false-interval":
            claim["result"]["bounds"] = [1.415, 1.416]
        elif name == "false-uniqueness":
            claim["result"]["unique"][0]["derivative"] = [-1, 4]
        elif name == "bridge-pole":
            cells = claim["result"]["cells"]
            index = next(i for i, cell in enumerate(cells[:-1]) if cell["domain"][1] == 0)
            span = [cells[index]["domain"][0], cells[index + 1]["domain"][1]]
            cells[index:index + 2] = [{"domain": span, "kind": "segment", "segment": [[span[0], 1 / span[0]], [span[1], 1 / span[1]]], "error_px": 0.1}]
        else:
            source["expr"] = "x^2+1/10"
        negative = out / (name + "-negative.json")
        bad_hash = write_packet(negative, source, claim)
        command = [binary, "--verify", str(negative)]
        bad = subprocess.run(command, capture_output=True, text=True, timeout=20)
        if bad.returncode != 1 or expected not in bad.stdout:
            raise ValueError((name, bad.returncode, bad.stdout, bad.stderr))
        rows.append({"id": name + "-negative", "argv": command, "exit": bad.returncode, "stdout": bad.stdout, "sha256": bad_hash})
    (out / "controls.json").write_text(json.dumps(rows, indent=2) + "\n")
    print("Four authentic claims verified and four rehashed semantic mutations rejected")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("out", type=Path)
    parser.add_argument("--binary", default="target/release/lucent")
    args = parser.parse_args()
    run(args.binary, args.out)
